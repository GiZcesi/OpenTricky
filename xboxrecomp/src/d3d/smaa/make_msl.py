#!/usr/bin/env python3
"""Convert the reference SMAA.hlsl (iryoku/smaa, MIT, unmodified in this folder) into Metal Shading Language source for the
macOS GPU backend: the code is kept, comments dropped, and the few HLSL-only constructs rewritten (out / inout parameters,
swizzles passed by reference, array parameters). Output: ../d3d8_gpu_smaa_msl.c (a C string, SMAA_MSL_BODY).
Run:  python3 make_msl.py"""
import re, sys, os

here = os.path.dirname(os.path.abspath(__file__))
s = open(os.path.join(here, "SMAA.hlsl"), encoding="latin-1").read()
license_text = re.search(r"/\*\*(.*?)\*/", s, flags=re.S)
t = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
t = re.sub(r"//[^\n]*", "", t)
t = re.sub(r"\n\s*\n+", "\n", t)

def sub(old, new, count=1):
    global t
    n = t.count(old)
    if n != count:
        sys.exit("expected %d of %r, found %d" % (count, old, n))
    t = t.replace(old, new)

# array parameters -> pointers (the vertex shader hands in a local array)
sub("out float4 offset[3]", "thread float4 *offset", 2)
sub("float4 offset[3]", "thread const float4 *offset", 6)
sub("out float2 pixcoord", "thread float2 &pixcoord")
sub("out float4 offset)", "thread float4 &offset)")
sub("out float2 e)", "thread float2 &e)", 2)
sub("inout float2 weights", "thread float2 &weights", 2)
# SMAAMovc: references to swizzles do not exist in MSL
sub("void SMAAMovc(bool2 cond, inout float2 variable, float2 value) {", "void SMAAMovc(bool2 cond, thread float2 &variable, float2 value) {")
t = re.sub(r"void SMAAMovc\(bool4 cond, inout float4 variable, float4 value\) \{.*?\n\}\n",
           "void SMAAMovc(bool4 cond, thread float4 &variable, float4 value) {\n"
           "    if (cond.x) variable.x = value.x;\n    if (cond.y) variable.y = value.y;\n"
           "    if (cond.z) variable.z = value.z;\n    if (cond.w) variable.w = value.w;\n}\n", t, count=1, flags=re.S)
# calls that pass a swizzle as an in/out argument: through a temporary
sub("SMAADetectHorizontalCornerPattern(SMAATexturePass2D(edgesTex), weights.rg, coords.xyzy, d);",
    "{ float2 wtmp = weights.rg; SMAADetectHorizontalCornerPattern(SMAATexturePass2D(edgesTex), wtmp, coords.xyzy, d); weights.rg = wtmp; }")
sub("SMAADetectVerticalCornerPattern(SMAATexturePass2D(edgesTex), weights.ba, coords.xyxz, d);",
    "{ float2 wtmp = weights.ba; SMAADetectVerticalCornerPattern(SMAATexturePass2D(edgesTex), wtmp, coords.xyxz, d); weights.ba = wtmp; }")
# the reference's platform sections (HLSL 3/4, GLSL) are dropped: SMAA_CUSTOM_SL with the macros of the prefix in d3d8_gpu_smaa.c
t = re.sub(r"#if defined\(SMAA_HLSL_3\)\n#define SMAATexture2D.*?#endif\n(?=#if defined\(SMAA_HLSL_4\))", "", t, count=1, flags=re.S)
t = re.sub(r"#if defined\(SMAA_HLSL_4\) \|\| defined\(SMAA_HLSL_4_1\).*?\n#endif\n#endif\n(?=#if defined\(SMAA_GLSL_3\))", "", t, count=1, flags=re.S)
t = re.sub(r"#if defined\(SMAA_GLSL_3\) \|\| defined\(SMAA_GLSL_4\).*?\n#endif\n(?=#if !defined\(SMAA_HLSL_3\))", "", t, count=1, flags=re.S)
t = re.sub(r"#if defined\(SMAA_HLSL_3\)\n#define SMAA_AREATEX_SELECT\(sample\) sample.ra\n#else\n#define SMAA_AREATEX_SELECT\(sample\) sample.rg\n#endif", "#define SMAA_AREATEX_SELECT(sample) sample.rg", t, count=1)
# the Texture2DMS separate pass uses SMAALoad: not defined here, the block is skipped by #ifdef

lines = t.split("\n")
out = []
out.append("/* d3d8_gpu_smaa_msl.c -- GENERATED by smaa/make_msl.py from smaa/SMAA.hlsl; do not edit.\n"
           " * SMAA (c) 2013 Jorge Jimenez, Jose I. Echevarria, Belen Masia, Fernando Navarro, Diego Gutierrez (MIT licence,\n"
           " * see smaa/LICENSE.txt), converted to Metal Shading Language. */\n")
out.append("const char SMAA_MSL_BODY[] =\n")
for ln in lines:
    esc = ln.replace("\\", "\\\\").replace('"', '\\"')
    out.append('    "%s\\n"\n' % esc)
out.append(";\n")
open(os.path.join(here, "..", "d3d8_gpu_smaa_msl.c"), "w").write("".join(out))
print("wrote d3d8_gpu_smaa_msl.c,", len(lines), "lines")
